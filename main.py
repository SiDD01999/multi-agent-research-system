def store_in_vectordb(content: str) -> VectorStore:
    """
    Store scraped content in ChromaDB
    """
    print("\n" + "="*60)
    print("PHASE 2: Vector Store Indexing")
    print("="*60)
    
    vs = VectorStore()
    
    # Clear existing content to avoid duplicates
    vs.clear()
    
    # Add content with metadata
    chunks_added = vs.add_documents(
        texts=[content],
        metadatas=[{"source": "nihongonext_website", "scraped_at": datetime.now().isoformat()}],
        chunk=True
    )
    
    print(f"\nIndexed {chunks_added} chunks into vector store")
    print(f"Stats: {vs.get_stats()}")
    
    return vs


def run_agent_analysis(vs: VectorStore, user_query: str) -> str:
    """
    Run the multi-agent analysis
    """
    print("\n" + "="*60)
    print("PHASE 3: Multi-Agent Analysis")
    print("="*60)
    
    crew = NihongoNextCrew(vector_store=vs)
    result = crew.run(user_query)
    
    return result


def save_proposal(content: str):
    """
    Save the final proposal to a markdown file
    """
    create_output_dir()
    output_path = os.path.join(OUTPUT_DIR, OUTPUT_FILENAME)
    
    # Add header with generation metadata
    final_content = f"""# NihongoNext Business Proposal

**Generated:** {datetime.now().strftime("%Y-%m-%d %H:%M:%S")}

**Generated by:** NihongoNext Multi-Agent Analysis System (Groq + Llama 3)

---

{content}

---

*This proposal was generated using AI-powered analysis of the NihongoNext platform.*
*Powered by Groq's ultra-fast LLM inference.*
"""
    
    with open(output_path, 'w', encoding='utf-8') as f:
        f.write(final_content)
    
    print(f"\n✅ Proposal saved to: {output_path}")
    return output_path


def main():
    """
    Main entry point - orchestrates the full analysis pipeline
    """
    print("\n" + "="*60)
    print("    NihongoNext Business Analysis Application")
    print("    Powered by Groq (Llama 3)")
    print("="*60)
    
    # Default user query
    user_query = """
    Analyze www.nihongonext.com and propose AI-driven features to enhance 
    the platform. Focus on:
    1. Identifying gaps in current offerings
    2. Opportunities for JLPT prep and business Japanese
    3. AI features to increase student retention
    4. Technical roadmap for implementation
    """
    
    try:
        # Phase 1: Scrape the website
        scraped_content = scrape_website()
        
        # Use fallback if scraping fails or returns little content
        if not scraped_content or len(scraped_content) < 200:
            print("\n⚠️  Using fallback content (website content limited)")
            scraped_content = get_fallback_content()
        
        # Phase 2: Store in vector database
        vector_store = store_in_vectordb(scraped_content)
        
        # Phase 3: Run multi-agent analysis
        proposal = run_agent_analysis(vector_store, user_query)
        
        # Phase 4: Save the proposal
        output_path = save_proposal(proposal)
        
        print("\n" + "="*60)
        print("    ✅ Analysis Complete!")
        print("="*60)
        print(f"\n📄 Proposal generated: {output_path}")
        print("\nOpen the file to view the complete business proposal.")
        
    except Exception as e:
        print(f"\n❌ Error during execution: {e}")
        import traceback
        traceback.print_exc()
        print("\nTroubleshooting tips:")
        print("1. Check your .env file contains GROQ_API_KEY")
        print("2. Verify your internet connection")
        raise


if __name__ == "__main__":
    main()

def create_output_dir():
    """Create output directory if it doesn't exist"""
    os.makedirs(OUTPUT_DIR, exist_ok=True)


def scrape_website() -> str:
    """
    Scrape NihongoNext website and return combined content
    """
    print("\n" + "="*60)
    print("PHASE 1: Web Scraping")
    print("="*60)
    
    try:
        scraper = NihongoNextScraper()
        content = scraper.get_combined_text()
        print(f"\nScraped {len(content)} characters of content")
        return content
    except Exception as e:
        print(f"\n⚠️  Scraping failed: {e}")
        print("Using fallback content...")
        return None


